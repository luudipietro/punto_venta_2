def _hero_settings(hero_images: list[str]) -> dict:
    return {"company_name": "Tienda", "logo_url": "/brand/logo.svg", "hero_images": hero_images}


def _fake_video(media_root: Path, name: str) -> list[Path]:
    videos = media_root / "videos"
    videos.mkdir(parents=True, exist_ok=True)
    files = [videos / f"{name}.mp4", videos / f"{name}.jpg"]
    for file in files:
        file.write_bytes(b"x")
    return files


@pytest.fixture
def cleanup_root(media_root: Path, monkeypatch) -> Path:
    settings = Settings(media_root=media_root, media_url="/media")
    monkeypatch.setattr(media, "get_settings", lambda: settings)
    return media_root


@pytest.mark.parametrize("origin", ["http://192.168.0.68:8000", "/api"])
async def test_removing_a_video_from_the_hero_deletes_it(
    client: AsyncClient, cleanup_root: Path, origin: str
) -> None:
    removed = _fake_video(cleanup_root, "removed")
    kept = _fake_video(cleanup_root, "kept")
    removed_url = f"{origin}/media/videos/removed.mp4"
    kept_url = f"{origin}/media/videos/kept.mp4"
    await client.put("/brand-settings", json=_hero_settings([removed_url, kept_url]))

    response = await client.put("/brand-settings", json=_hero_settings([kept_url]))

    assert response.status_code == 200, response.text
    assert not any(file.exists() for file in removed)
    assert all(file.exists() for file in kept)


async def test_discarding_an_unsaved_upload_deletes_it(
    client: AsyncClient, cleanup_root: Path
) -> None:
    files = _fake_video(cleanup_root, "unsaved")

    response = await client.post(
        "/brand-settings/discard-upload", json={"url": "/media/videos/unsaved.mp4"}
    )

    assert response.status_code == 204
    assert not any(file.exists() for file in files)


async def test_discarding_never_deletes_a_saved_hero_video(
    client: AsyncClient, cleanup_root: Path
) -> None:
    files = _fake_video(cleanup_root, "saved")
    url = "/media/videos/saved.mp4"
    await client.put("/brand-settings", json=_hero_settings([url]))

    response = await client.post("/brand-settings/discard-upload", json={"url": url})

    assert response.status_code == 204
    assert all(file.exists() for file in files)


