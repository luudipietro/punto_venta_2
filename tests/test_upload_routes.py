def _make_video(
    path: Path, *, size: str = "320x240", seconds: int = 2, audio: bool = True
) -> bytes:
    """A real (synthetic) clip, generated by the same ffmpeg."""
    subprocess.run(
        [
            imageio_ffmpeg.get_ffmpeg_exe(),
            "-loglevel", "error", "-y",
            "-f", "lavfi", "-i", f"testsrc=size={size}:rate=60:duration={seconds}",
            *(["-f", "lavfi", "-i", f"sine=duration={seconds}"] if audio else []),
            "-c:v", "libx264", "-preset", "ultrafast", "-c:a", "aac", "-shortest",
            "-metadata", "location=-34.6037-058.3816/",
            str(path),
        ],
        check=True,
    )  # fmt: skip
    return path.read_bytes()


def _probe(path: Path) -> str:
    return subprocess.run(
        [imageio_ffmpeg.get_ffmpeg_exe(), "-hide_banner", "-i", str(path)],
        capture_output=True,
        text=True,
        check=False,
    ).stderr


async def _upload(
    client: AsyncClient, content: bytes, content_type: str = "video/mp4", query: str = ""
):
    return await client.post(
        f"/uploads/videos{query}", files={"file": ("clip.mp4", content, content_type)}
    )


def _stored_files(media_root: Path) -> list[Path]:
    return list((media_root / "videos").glob("*"))


async def test_upload_video_converts_it_and_creates_a_poster(
    client: AsyncClient, media_root: Path, tmp_path: Path
) -> None:
    source = _make_video(tmp_path / "in.mov", size="1920x1080")

    response = await _upload(client, source, "video/quicktime")

    assert response.status_code == 201, response.text
    url = response.json()["url"]
    assert url.startswith("/media/videos/") and url.endswith(".mp4")
    stored = media_root / url.removeprefix("/media/")
    poster = stored.with_suffix(".jpg")
    assert poster.read_bytes().startswith(b"\xff\xd8")
    info = _probe(stored)
    assert "h264" in info
    assert "aac" in info
    assert "1280x720" in info
    assert "30 fps" in info
    assert "location" not in info


