async def test_upload_video_is_admin_only(
    client_no_auth: AsyncClient, db_session: AsyncSession, media_root: Path
) -> None:
    branch = await SqlAlchemyBranchRepository(db_session).create(Branch(name="Central"))
    users = UserService(
        SqlAlchemyUserRepository(db_session), SqlAlchemyBranchRepository(db_session)
    )
    await users.create("empleado1", "pass1234", UserRole.EMPLEADO, branch.id)
    await db_session.commit()
    login = await client_no_auth.post(
        "/auth/login", json={"username": "empleado1", "password": "pass1234"}
    )

    response = await client_no_auth.post(
        "/uploads/videos",
        files={"file": ("clip.mp4", b"x", "video/mp4")},
        headers={"Authorization": f"Bearer {login.json()['access_token']}"},
    )

    assert response.status_code == 403


@pytest.mark.parametrize("prefix", ["/media", "/api/media"])
async def test_media_is_served_by_ranges(prefix: str, tmp_path: Path, monkeypatch) -> None:
    """iPhone Safari refuses to play a video from a server that ignores
    `Range` requests."""
    (tmp_path / "clip.mp4").write_bytes(b"0123456789")
    settings = Settings(media_root=tmp_path, media_url="/media")
    monkeypatch.setattr(main, "get_settings", lambda: settings)
    transport = ASGITransport(app=main.create_app())

    async with AsyncClient(transport=transport, base_url="http://test") as client:
        response = await client.get(f"{prefix}/clip.mp4", headers={"Range": "bytes=2-5"})

    assert response.status_code == 206
    assert response.content == b"2345"
    assert response.headers["content-type"] == "video/mp4"
